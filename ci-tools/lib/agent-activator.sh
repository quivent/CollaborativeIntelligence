#!/usr/bin/env bash
# agent-activator.sh - Optimized agent activation shortcuts
# Part of the Collaborative Intelligence optimization implementation

# Determine script directory
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CI_TOOLS_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
CI_ROOT_DIR="$(cd "$CI_TOOLS_DIR/.." && pwd)"

# Import common library
source "$SCRIPT_DIR/common.sh"

# Import memory optimization bridge if available
if [[ -f "$SCRIPT_DIR/rust-memory-bridge.sh" ]]; then
  source "$SCRIPT_DIR/rust-memory-bridge.sh"
  MEMORY_OPTIMIZATION_AVAILABLE=true
else
  MEMORY_OPTIMIZATION_AVAILABLE=false
fi

# Optimized activation function for @@ syntax
activate_at() {
  local agent_name="${1#@@}"
  local context="${2:-}"
  
  # Validate agent name
  if [[ -z "$agent_name" ]]; then
    echo "Error: No agent name provided after @@ symbol" >&2
    echo "Usage: @@<agent_name> [context]" >&2
    exit 1
  fi
  
  # Call the full activation command
  "$CI_TOOLS_DIR/cmd/agent.sh" activate "$agent_name" "$context"
}

# Optimized activation function for > syntax
activate_hash() {
  local agent_name="${1#>}"
  local context="${2:-}"
  
  # Validate agent name
  if [[ -z "$agent_name" ]]; then
    echo "Error: No agent name provided after > symbol" >&2
    echo "Usage: ><agent_name> [context]" >&2
    exit 1
  fi
  
  # Call the full activation command
  "$CI_TOOLS_DIR/cmd/agent.sh" activate "$agent_name" "$context"
}

# Create agent cache entry with optimization support
create_optimized_agent_cache() {
  local agent_name="$1"
  local directory="$2"
  local initializer="$3"
  local intent="$4"
  
  # Use memory optimization if available
  if [[ "$MEMORY_OPTIMIZATION_AVAILABLE" == "true" ]]; then
    debug_log "Using optimized memory system for agent cache creation"
    create_agent_cache "$agent_name" "$directory" "$initializer" "$intent"
    return $?
  else
    debug_log "Using legacy agent cache creation"
    # Legacy implementation - this will be removed in the future
    local timestamp=$(date +%s)
    local cache_dir="$CI_ROOT_DIR/CACHE/SESSIONS"
    local cache_file="$cache_dir/${agent_name}_${directory//\//_}_${initializer}_$timestamp.md"
    
    # Create cache directory if it doesn't exist
    mkdir -p "$cache_dir"
    
    # Create cache file with markdown format
    cat > "$cache_file" << EOF
# Agent Activation Cache

## Metadata
- **Agent:** $agent_name
- **Working Directory:** $directory
- **Initializer:** $initializer
- **Timestamp:** $(date)

## Intent
$intent

## Status
Active

This file was automatically generated by the Agent Cache System and should be immediately integrated into the agent's short-term memory upon activation.
EOF
    
    # Update terminal title
    echo -ne "\033]0;Agent: $agent_name\007"
    
    return 0
  fi
}

# Load agent memory with optimization support
load_optimized_agent_memory() {
  local agent_name="$1"
  local context="$2"
  
  # Use memory optimization if available
  if [[ "$MEMORY_OPTIMIZATION_AVAILABLE" == "true" ]]; then
    debug_log "Using optimized memory system for agent memory loading"
    load_agent_memory "$agent_name" "$context" "markdown"
    return $?
  else
    debug_log "Using legacy agent memory loading"
    # Legacy implementation - this will be removed in the future
    local agent_dir="$CI_ROOT_DIR/AGENTS/$agent_name"
    local memory_file="$agent_dir/MEMORY.md"
    local learning_file="$agent_dir/ContinuousLearning.md"
    
    # Check if agent directory exists
    if [[ ! -d "$agent_dir" ]]; then
      print_error "Agent not found: $agent_name"
      return 1
    fi
    
    # Output memory contents
    if [[ -f "$memory_file" ]]; then
      cat "$memory_file"
      echo -e "\n\n# Continuous Learning\n"
    fi
    
    if [[ -f "$learning_file" ]]; then
      cat "$learning_file"
    fi
    
    # If context is provided, look for context-specific files
    if [[ -n "$context" ]]; then
      local context_files=($(find "$agent_dir/Sessions" -type f -name "*${context}*.md" 2>/dev/null))
      
      if [[ ${#context_files[@]} -gt 0 ]]; then
        echo -e "\n\n# Context-Specific Memory: $context\n"
        
        for file in "${context_files[@]}"; do
          echo -e "## $(basename "$file" .md)\n"
          cat "$file"
          echo -e "\n"
        done
      fi
    fi
    
    return 0
  fi
}

# Main function to determine activation method
main() {
  local first_arg="${1:-}"
  
  # Check if this is an @@ activation
  if [[ "$first_arg" == @@* ]]; then
    activate_at "$@"
    exit $?
  fi
  
  # Check if this is a > activation
  if [[ "$first_arg" == >* ]]; then
    activate_hash "$@"
    exit $?
  fi
  
  # If not a special activation, show usage
  echo "Usage:"
  echo "  @@<agent_name> [context] - Activate agent using @@ syntax"
  echo "  ><agent_name> [context] - Activate agent using > syntax"
  echo ""
  echo "Example:"
  echo "  @@Athena - Activate Athena agent"
  echo "  >Debugger code - Activate Debugger agent with 'code' context"
  exit 1
}

# Debug logging function
debug_log() {
  if [[ "${MEMORY_DEBUG:-false}" == "true" ]]; then
    echo "[DEBUG] $1" >&2
  fi
}

# Export functions
export -f create_optimized_agent_cache
export -f load_optimized_agent_memory

# Run main function if script is executed directly
if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
  main "$@"
fi