use std::fs::{self, create_dir_all};
use std::path::{Path, PathBuf};
use std::time::{SystemTime, UNIX_EPOCH};
use std::io::Write;
use std::error::Error;

/// Creates a cache file for an agent activation
/// 
/// # Arguments
/// * `agent_name` - Name of the agent
/// * `directory` - Working directory
/// * `initializer` - Who activated the agent
/// * `intent` - Why the agent was activated
/// 
/// # Returns
/// * `Result<String, Box<dyn Error>>` - The path to the created cache file or an error
pub fn create_agent_cache(
    agent_name: &str,
    directory: &str,
    initializer: &str,
    intent: &str,
) -> Result<String, Box<dyn Error>> {
    let cache_dir = Path::new("/Users/joshkornreich/Documents/Projects/CollaborativeIntelligence/CACHE/SESSIONS");
    
    // Ensure CACHE directory exists
    create_dir_all(cache_dir)?;
    
    // Sanitize filename components
    let sanitize = |s: &str| -> String {
        s.replace(' ', "_")
            .chars()
            .filter(|c| c.is_alphanumeric() || *c == '_' || *c == '-' || *c == '.')
            .collect()
    };
    
    let safe_agent = sanitize(agent_name);
    let safe_dir = sanitize(directory);
    let safe_initializer = sanitize(initializer);
    
    // Create filename
    let timestamp = SystemTime::now()
        .duration_since(UNIX_EPOCH)?
        .as_secs();
    
    let filename = format!("{}_{}_{}_{}.md", safe_agent, safe_dir, safe_initializer, timestamp);
    let cache_file_path = cache_dir.join(filename);
    
    // Get current date and time as string
    let datetime = chrono::Local::now().format("%Y-%m-%d %H:%M:%S").to_string();
    
    // Create cache file with agent information
    let content = format!(
        r#"# Agent Activation Cache

## Metadata
- **Agent:** {}
- **Working Directory:** {}
- **Initializer:** {}
- **Timestamp:** {}

## Intent
{}

## Status
Active

This file was automatically generated by the Agent Cache System and should be immediately integrated into the agent's short-term memory upon activation.
"#,
        agent_name, directory, initializer, datetime, intent
    );
    
    let mut file = fs::File::create(&cache_file_path)?;
    file.write_all(content.as_bytes())?;
    
    Ok(cache_file_path.to_string_lossy().to_string())
}

/// Reads a cache file
/// 
/// # Arguments
/// * `cache_file_path` - Path to the cache file
/// 
/// # Returns
/// * `Result<String, Box<dyn Error>>` - The content of the cache file or an error
pub fn read_agent_cache(cache_file_path: &str) -> Result<String, Box<dyn Error>> {
    let content = fs::read_to_string(cache_file_path)?;
    Ok(content)
}

/// Lists all active agent cache files
/// 
/// # Returns
/// * `Result<Vec<String>, Box<dyn Error>>` - List of paths to active cache files or an error
pub fn list_active_agents() -> Result<Vec<String>, Box<dyn Error>> {
    let cache_dir = Path::new("/Users/joshkornreich/Documents/Projects/CollaborativeIntelligence/CACHE/SESSIONS");
    
    if !cache_dir.exists() {
        return Ok(Vec::new());
    }
    
    let mut active_agents = Vec::new();
    
    for entry in fs::read_dir(cache_dir)? {
        let entry = entry?;
        let path = entry.path();
        
        if path.is_file() && path.extension().map_or(false, |ext| ext == "md") {
            let content = fs::read_to_string(&path)?;
            if content.contains("## Status\nActive") {
                active_agents.push(path.to_string_lossy().to_string());
            }
        }
    }
    
    active_agents.sort();
    Ok(active_agents)
}

/// Gets the most recent cache file for a specific agent
/// 
/// # Arguments
/// * `agent_name` - Name of the agent
/// 
/// # Returns
/// * `Result<Option<String>, Box<dyn Error>>` - The path to the most recent cache file or None if not found
pub fn get_latest_agent_cache(agent_name: &str) -> Result<Option<String>, Box<dyn Error>> {
    let cache_dir = Path::new("/Users/joshkornreich/Documents/Projects/CollaborativeIntelligence/CACHE/SESSIONS");
    
    if !cache_dir.exists() {
        return Ok(None);
    }
    
    let safe_agent = agent_name.replace(' ', "_")
        .chars()
        .filter(|c| c.is_alphanumeric() || *c == '_' || *c == '-' || *c == '.')
        .collect::<String>();
    
    let mut latest_path: Option<PathBuf> = None;
    let mut latest_time = 0;
    
    for entry in fs::read_dir(cache_dir)? {
        let entry = entry?;
        let path = entry.path();
        
        if path.is_file() && path.extension().map_or(false, |ext| ext == "md") {
            let filename = path.file_name().unwrap().to_string_lossy();
            if filename.starts_with(&format!("{}_", safe_agent)) {
                let metadata = fs::metadata(&path)?;
                let modified = metadata.modified()?.duration_since(UNIX_EPOCH)?.as_secs();
                
                if latest_path.is_none() || modified > latest_time {
                    latest_path = Some(path.clone());
                    latest_time = modified;
                }
            }
        }
    }
    
    Ok(latest_path.map(|p| p.to_string_lossy().to_string()))
}

/// Marks an agent cache as inactive
/// 
/// # Arguments
/// * `cache_file_path` - Path to the cache file
/// 
/// # Returns
/// * `Result<(), Box<dyn Error>>` - Success or error
pub fn deactivate_agent_cache(cache_file_path: &str) -> Result<(), Box<dyn Error>> {
    let content = fs::read_to_string(cache_file_path)?;
    let updated_content = content.replace("## Status\nActive", "## Status\nInactive");
    
    fs::write(cache_file_path, updated_content)?;
    Ok(())
}

/// Cleans up old cache files (older than 7 days)
/// 
/// # Returns
/// * `Result<usize, Box<dyn Error>>` - Number of files removed or an error
pub fn cleanup_old_cache() -> Result<usize, Box<dyn Error>> {
    let cache_dir = Path::new("/Users/joshkornreich/Documents/Projects/CollaborativeIntelligence/CACHE/SESSIONS");
    
    if !cache_dir.exists() {
        return Ok(0);
    }
    
    let now = SystemTime::now();
    let seven_days = std::time::Duration::from_secs(7 * 24 * 60 * 60);
    let mut removed_count = 0;
    
    for entry in fs::read_dir(cache_dir)? {
        let entry = entry?;
        let path = entry.path();
        
        if path.is_file() && path.extension().map_or(false, |ext| ext == "md") {
            let metadata = fs::metadata(&path)?;
            if let Ok(modified) = metadata.modified() {
                if let Ok(duration) = now.duration_since(modified) {
                    if duration > seven_days {
                        fs::remove_file(&path)?;
                        removed_count += 1;
                    }
                }
            }
        }
    }
    
    Ok(removed_count)
}