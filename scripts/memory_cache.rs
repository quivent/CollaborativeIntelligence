// Memory Cache System
// Pure Rust implementation of agent memory caching with various performance optimizations

// Error type for cache operations
#[derive(Debug)]
pub enum MemoryCacheError {
    IoError(io::Error),
    JsonError(serde_json::Error),
    ConfigError(String),
    ValidationError(String),
}

impl From<io::Error> for MemoryCacheError {
    fn from(err: io::Error) -> Self {
        MemoryCacheError::IoError(err)
    }
}

impl From<serde_json::Error> for MemoryCacheError {
    fn from(err: serde_json::Error) -> Self {
        MemoryCacheError::JsonError(err)
    }
}

impl std::fmt::Display for MemoryCacheError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            MemoryCacheError::IoError(e) => write!(f, "I/O error: {}", e),
            MemoryCacheError::JsonError(e) => write!(f, "JSON error: {}", e),
            MemoryCacheError::ConfigError(e) => write!(f, "Configuration error: {}", e),
            MemoryCacheError::ValidationError(e) => write!(f, "Validation error: {}", e),
        }
    }
}

impl std::error::Error for MemoryCacheError {}

type Result<T> = std::result::Result<T, MemoryCacheError>;

// Agent status enum
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum AgentStatus {
    Active,
    Inactive,
}

// Cache entry structure
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AgentCacheEntry {
    pub agent_name: String,
    pub directory: String,
    pub initializer: String,
    pub timestamp: u64, // Unix timestamp
    pub intent: String,
    pub status: AgentStatus,
    
    #[serde(skip)]
    pub modified: bool,
}

impl AgentCacheEntry {
    // Create a new cache entry
    pub fn new(agent_name: &str, directory: &str, initializer: &str, intent: &str) -> Self {
        let timestamp = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .expect("Time went backwards")
            .as_secs();
        
        Self {
            agent_name: agent_name.to_string(),
            directory: directory.to_string(),
            initializer: initializer.to_string(),
            timestamp,
            intent: intent.to_string(),
            status: AgentStatus::Active,
            modified: true,
        }
    }
    
    // Convert to markdown format
    pub fn to_markdown(&self) -> String {
        let timestamp_readable = chrono::DateTime::<chrono::Utc>::from_utc(
            chrono::NaiveDateTime::from_timestamp_opt(self.timestamp as i64, 0).unwrap(),
            chrono::Utc,
        ).format("%Y-%m-%d %H:%M:%S UTC");
        
        format!(
            r#"# Agent Activation Cache

## Metadata
- **Agent:** {}
- **Working Directory:** {}
- **Initializer:** {}
- **Timestamp:** {}

## Intent
{}

## Status
{}

This file was automatically generated by the Agent Cache System and should be immediately integrated into the agent's short-term memory upon activation.
"#,
            self.agent_name,
            self.directory,
            self.initializer,
            timestamp_readable,
            self.intent,
            match self.status {
                AgentStatus::Active => "Active",
                AgentStatus::Inactive => "Inactive",
            }
        )
    }
}

// Memory segment structures
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct MemorySegment {
    pub id: String,
    pub content: String,
    pub source_file: String,
    pub domains: Vec<String>,
    pub priority: u8,
    pub timestamp: u64,
}

// Cache configuration
#[derive(Debug, Clone)]
pub struct MemoryCacheConfig {
    pub cache_dir: PathBuf,
    pub database_path: PathBuf,
    pub persistence_interval: Duration,
    pub segment_size: usize,
    pub segment_overlap: usize,
    pub enable_segmentation: bool,
    pub enable_compression: bool,
    pub cache_capacity: usize,
    pub debug: bool,
}

impl Default for MemoryCacheConfig {
    fn default() -> Self {
        Self {
            cache_dir: PathBuf::from("CACHE/SESSIONS"),
            database_path: PathBuf::from("memory.db.json"),
            persistence_interval: Duration::from_secs(60),
            segment_size: 4096,
            segment_overlap: 256,
            enable_segmentation: true,
            enable_compression: false,
            cache_capacity: 100,
            debug: false,
        }
    }
}

// Main cache system
pub struct MemoryCache {
    config: MemoryCacheConfig,
    entries: Arc<RwLock<HashMap<String, AgentCacheEntry>>>,
    memory_segments: Arc<RwLock<HashMap<String, Vec<MemorySegment>>>>,
    last_persistence: Arc<Mutex<SystemTime>>,
    modified: Arc<Mutex<bool>>,
}

impl MemoryCache {
    // Create a new cache instance
    pub fn new(config: MemoryCacheConfig) -> Result<Self> {
        // Ensure cache directory exists
        fs::create_dir_all(&config.cache_dir)?;
        
        let cache = Self {
            config,
            entries: Arc::new(RwLock::new(HashMap::new())),
            memory_segments: Arc::new(RwLock::new(HashMap::new())),
            last_persistence: Arc::new(Mutex::new(SystemTime::now())),
            modified: Arc::new(Mutex::new(false)),
        };
        
        // Initialize by loading existing data
        cache.load_existing_entries()?;
        
        // Start persistence thread if interval is non-zero
        if cache.config.persistence_interval.as_secs() > 0 {
            cache.start_persistence_thread();
        }
        
        Ok(cache)
    }
    
    // Debug logging
    fn debug_log(&self, message: &str) {
        if self.config.debug {
            eprintln!("[Memory Cache Debug] {}", message);
        }
    }
    
    // Start a background thread for periodic persistence
    fn start_persistence_thread(&self) {
        let config = self.config.clone();
        let entries = Arc::clone(&self.entries);
        let last_persistence = Arc::clone(&self.last_persistence);
        let modified = Arc::clone(&self.modified);
        
        thread::spawn(move || {
            loop {
                thread::sleep(Duration::from_secs(1));
                
                // Check if persistence is due
                let now = SystemTime::now();
                let should_persist = {
                    let last = last_persistence.lock().unwrap();
                    now.duration_since(*last).unwrap_or(Duration::from_secs(0)) >= config.persistence_interval
                };
                
                if should_persist {
                    // Check if modified
                    let is_modified = {
                        let modified_guard = modified.lock().unwrap();
                        *modified_guard
                    };
                    
                    if is_modified {
                        // Persist to disk
                        let entries_guard = entries.read().unwrap();
                        
                        for (id, entry) in entries_guard.iter() {
                            if entry.modified {
                                let path = config.cache_dir.join(format!("{}.md", id));
                                let content = entry.to_markdown();
                                if let Err(e) = fs::write(&path, content) {
                                    eprintln!("Error writing cache file {}: {}", path.display(), e);
                                }
                            }
                        }
                        
                        // Update persistence time and modified flag
                        {
                            let mut last = last_persistence.lock().unwrap();
                            *last = now;
                        }
                        {
                            let mut modified_guard = modified.lock().unwrap();
                            *modified_guard = false;
                        }
                    }
                }
            }
        });
    }
    
    // Load existing cache entries from disk
    fn load_existing_entries(&self) -> Result<()> {
        self.debug_log("Loading existing cache entries");
        
        if !self.config.cache_dir.exists() {
            return Ok(());
        }
        
        for entry in fs::read_dir(&self.config.cache_dir)? {
            let entry = entry?;
            let path = entry.path();
            
            if path.is_file() && path.extension().map_or(false, |ext| ext == "md") {
                let content = fs::read_to_string(&path)?;
                
                if let Some(entry) = self.parse_cache_file(&content) {
                    let file_name = path
                        .file_name()
                        .unwrap()
                        .to_string_lossy()
                        .replace(".md", "");
                    
                    let mut entries = self.entries.write().unwrap();
                    entries.insert(file_name, entry);
                }
            }
        }
        
        Ok(())
    }
    
    // Parse a markdown cache file into an entry
    fn parse_cache_file(&self, content: &str) -> Option<AgentCacheEntry> {
        self.debug_log("Parsing cache file");
        
        let mut agent_name = String::new();
        let mut directory = String::new();
        let mut initializer = String::new();
        let mut intent = String::new();
        let mut status = AgentStatus::Inactive;
        let mut in_intent_section = false;
        
        for line in content.lines() {
            if line.starts_with("- **Agent:**") {
                agent_name = line.trim_start_matches("- **Agent:**").trim().to_string();
            } else if line.starts_with("- **Working Directory:**") {
                directory = line.trim_start_matches("- **Working Directory:**").trim().to_string();
            } else if line.starts_with("- **Initializer:**") {
                initializer = line.trim_start_matches("- **Initializer:**").trim().to_string();
            } else if line.starts_with("## Intent") {
                in_intent_section = true;
                continue;
            } else if line.starts_with("## Status") {
                in_intent_section = false;
            } else if in_intent_section && !line.is_empty() {
                if !intent.is_empty() {
                    intent.push('\n');
                }
                intent.push_str(line);
            } else if line.trim() == "Active" {
                status = AgentStatus::Active;
            } else if line.trim() == "Inactive" {
                status = AgentStatus::Inactive;
            }
        }
        
        if agent_name.is_empty() || directory.is_empty() || initializer.is_empty() {
            return None;
        }
        
        Some(AgentCacheEntry {
            agent_name,
            directory,
            initializer,
            timestamp: SystemTime::now()
                .duration_since(UNIX_EPOCH)
                .unwrap()
                .as_secs(),
            intent,
            status,
            modified: false,
        })
    }
    
    // Create a new agent cache entry
    pub fn create_agent_cache(
        &self,
        agent_name: &str,
        directory: &str,
        initializer: &str,
        intent: &str,
    ) -> Result<String> {
        self.debug_log(&format!("Creating cache for agent {}", agent_name));
        
        // Create the entry
        let entry = AgentCacheEntry::new(agent_name, directory, initializer, intent);
        
        // Generate entry ID
        let timestamp = entry.timestamp;
        let sanitized_agent = sanitize_for_filename(agent_name);
        let sanitized_dir = sanitize_for_filename(directory);
        let sanitized_init = sanitize_for_filename(initializer);
        
        let entry_id = format!(
            "{}_{}_{}_{}",
            sanitized_agent,
            sanitized_dir,
            sanitized_init,
            timestamp
        );
        
        // Store in memory cache
        {
            let mut entries = self.entries.write().unwrap();
            entries.insert(entry_id.clone(), entry);
            
            // Set modified flag
            let mut modified = self.modified.lock().unwrap();
            *modified = true;
        }
        
        // Maybe persist now if interval is zero (immediate persistence)
        if self.config.persistence_interval.as_secs() == 0 {
            self.force_persist()?;
        }
        
        Ok(entry_id)
    }
    
    // Force immediate persistence to disk
    pub fn force_persist(&self) -> Result<()> {
        self.debug_log("Forcing persistence to disk");
        
        let entries = self.entries.read().unwrap();
        
        for (id, entry) in entries.iter() {
            if entry.modified {
                let path = self.config.cache_dir.join(format!("{}.md", id));
                let content = entry.to_markdown();
                fs::write(&path, content)?;
            }
        }
        
        // Update persistence time and modified flag
        {
            let mut last = self.last_persistence.lock().unwrap();
            *last = SystemTime::now();
        }
        {
            let mut modified = self.modified.lock().unwrap();
            *modified = false;
        }
        
        Ok(())
    }
    
    // Get all active agents
    pub fn get_active_agents(&self) -> Vec<String> {
        self.debug_log("Getting active agents");
        
        let entries = self.entries.read().unwrap();
        let mut active_agents = Vec::new();
        
        for entry in entries.values() {
            if entry.status == AgentStatus::Active && !active_agents.contains(&entry.agent_name) {
                active_agents.push(entry.agent_name.clone());
            }
        }
        
        active_agents
    }
    
    // Get latest entry for a specific agent
    pub fn get_entry_for_agent(&self, agent_name: &str) -> Option<AgentCacheEntry> {
        self.debug_log(&format!("Getting entry for agent {}", agent_name));
        
        let entries = self.entries.read().unwrap();
        let mut latest_entry = None;
        let mut latest_time = 0;
        
        for entry in entries.values() {
            if entry.agent_name == agent_name && entry.status == AgentStatus::Active {
                if latest_entry.is_none() || entry.timestamp > latest_time {
                    latest_entry = Some(entry.clone());
                    latest_time = entry.timestamp;
                }
            }
        }
        
        latest_entry
    }
    
    // Deactivate an agent
    pub fn deactivate_agent(&self, agent_name: &str) -> Result<()> {
        self.debug_log(&format!("Deactivating agent {}", agent_name));
        
        let mut modified = false;
        
        {
            let mut entries = self.entries.write().unwrap();
            
            for entry in entries.values_mut() {
                if entry.agent_name == agent_name && entry.status == AgentStatus::Active {
                    entry.status = AgentStatus::Inactive;
                    entry.modified = true;
                    modified = true;
                }
            }
        }
        
        if modified {
            let mut m = self.modified.lock().unwrap();
            *m = true;
            
            // Force persist if immediate persistence
            if self.config.persistence_interval.as_secs() == 0 {
                self.force_persist()?;
            }
        }
        
        Ok(())
    }
    
    // Clean up old cache entries
    pub fn cleanup_old_entries(&self, days: u64) -> Result<usize> {
        self.debug_log(&format!("Cleaning up entries older than {} days", days));
        
        let seconds = days * 24 * 60 * 60;
        let now = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .expect("Time went backwards")
            .as_secs();
        
        let mut to_remove = Vec::new();
        
        // Identify entries to remove
        {
            let entries = self.entries.read().unwrap();
            
            for (id, entry) in entries.iter() {
                if entry.status == AgentStatus::Inactive && now - entry.timestamp > seconds {
                    to_remove.push(id.clone());
                }
            }
        }
        
        // Remove identified entries
        let mut removed_count = 0;
        {
            let mut entries = self.entries.write().unwrap();
            
            for id in &to_remove {
                entries.remove(id);
                
                // Remove from disk as well
                let path = self.config.cache_dir.join(format!("{}.md", id));
                if path.exists() {
                    if let Err(e) = fs::remove_file(&path) {
                        self.debug_log(&format!("Error removing file {}: {}", path.display(), e));
                    } else {
                        removed_count += 1;
                    }
                }
            }
        }
        
        Ok(removed_count)
    }
    
    // Load memory segments for an agent
    pub fn load_memory_segments(
        &self,
        agent_name: &str,
        context: Option<&str>,
        agents_dir: &Path,
    ) -> Result<Vec<MemorySegment>> {
        self.debug_log(&format!("Loading memory segments for agent {}", agent_name));
        
        // Check if we have cached segments
        {
            let segments = self.memory_segments.read().unwrap();
            let cache_key = format!("{}:{}", agent_name, context.unwrap_or("general"));
            
            if let Some(cached) = segments.get(&cache_key) {
                self.debug_log("Using cached memory segments");
                return Ok(cached.clone());
            }
        }
        
        let agent_dir = agents_dir.join(agent_name);
        let memory_file = agent_dir.join("MEMORY.md");
        let learning_file = agent_dir.join("ContinuousLearning.md");
        
        if !agent_dir.exists() {
            return Err(MemoryCacheError::ValidationError(format!("Agent not found: {}", agent_name)));
        }
        
        let mut result = Vec::new();
        
        // Process memory file
        if memory_file.exists() {
            let content = fs::read_to_string(&memory_file)?;
            
            // If segmentation is enabled, split content into segments
            if self.config.enable_segmentation {
                let segments = self.segment_content(
                    &content,
                    memory_file.to_string_lossy().to_string(),
                    vec!["core".to_string()],
                    "CORE_MEMORY",
                );
                result.extend(segments);
            } else {
                // Otherwise, create a single segment
                result.push(MemorySegment {
                    id: "MEMORY".to_string(),
                    content,
                    source_file: memory_file.to_string_lossy().to_string(),
                    domains: vec!["core".to_string()],
                    priority: 10,
                    timestamp: fs::metadata(&memory_file)?
                        .modified()?
                        .duration_since(UNIX_EPOCH)
                        .unwrap()
                        .as_secs(),
                });
            }
        }
        
        // Process learning file
        if learning_file.exists() {
            let content = fs::read_to_string(&learning_file)?;
            
            // If segmentation is enabled, split content into segments
            if self.config.enable_segmentation {
                let segments = self.segment_content(
                    &content,
                    learning_file.to_string_lossy().to_string(),
                    vec!["learning".to_string()],
                    "LEARNING",
                );
                result.extend(segments);
            } else {
                // Otherwise, create a single segment
                result.push(MemorySegment {
                    id: "CONTINUOUS_LEARNING".to_string(),
                    content,
                    source_file: learning_file.to_string_lossy().to_string(),
                    domains: vec!["learning".to_string()],
                    priority: 8,
                    timestamp: fs::metadata(&learning_file)?
                        .modified()?
                        .duration_since(UNIX_EPOCH)
                        .unwrap()
                        .as_secs(),
                });
            }
        }
        
        // Process context-specific files if context was provided
        if let Some(ctx) = context {
            let sessions_dir = agent_dir.join("Sessions");
            
            if sessions_dir.exists() {
                // Find files matching the context
                for entry in fs::read_dir(sessions_dir)? {
                    let entry = entry?;
                    let path = entry.path();
                    
                    if path.is_file() && path.extension().map_or(false, |ext| ext == "md") {
                        if let Some(file_name) = path.file_name() {
                            let file_name_str = file_name.to_string_lossy().to_lowercase();
                            
                            if file_name_str.contains(&ctx.to_lowercase()) {
                                let content = fs::read_to_string(&path)?;
                                let domains = vec!["context".to_string(), ctx.to_lowercase()];
                                
                                // If segmentation is enabled, split content into segments
                                if self.config.enable_segmentation {
                                    let id_base = file_name.to_string_lossy().replace(".md", "").to_uppercase();
                                    let segments = self.segment_content(
                                        &content, 
                                        path.to_string_lossy().to_string(),
                                        domains,
                                        &id_base,
                                    );
                                    result.extend(segments);
                                } else {
                                    // Otherwise, create a single segment
                                    result.push(MemorySegment {
                                        id: file_name.to_string_lossy().replace(".md", "").to_uppercase(),
                                        content,
                                        source_file: path.to_string_lossy().to_string(),
                                        domains,
                                        priority: 5,
                                        timestamp: fs::metadata(&path)?
                                            .modified()?
                                            .duration_since(UNIX_EPOCH)
                                            .unwrap()
                                            .as_secs(),
                                    });
                                }
                            }
                        }
                    }
                }
            }
        }
        
        // Sort segments by priority (highest first)
        result.sort_by(|a, b| b.priority.cmp(&a.priority));
        
        // Cache the result for future use
        {
            let mut segments = self.memory_segments.write().unwrap();
            let cache_key = format!("{}:{}", agent_name, context.unwrap_or("general"));
            segments.insert(cache_key, result.clone());
        }
        
        Ok(result)
    }
    
    // Split content into segments
    fn segment_content(
        &self,
        content: &str,
        source_file: String,
        domains: Vec<String>,
        id_base: &str,
    ) -> Vec<MemorySegment> {
        self.debug_log(&format!("Segmenting content from {}", source_file));
        
        let mut segments = Vec::new();
        
        // If segmentation is disabled, return a single segment
        if !self.config.enable_segmentation {
            segments.push(MemorySegment {
                id: id_base.to_string(),
                content: content.to_string(),
                source_file,
                domains,
                priority: 10,
                timestamp: SystemTime::now()
                    .duration_since(UNIX_EPOCH)
                    .unwrap()
                    .as_secs(),
            });
            return segments;
        }
        
        // If content is shorter than segment size, return a single segment
        if content.len() <= self.config.segment_size {
            segments.push(MemorySegment {
                id: format!("{}_1", id_base),
                content: content.to_string(),
                source_file,
                domains,
                priority: 10,
                timestamp: SystemTime::now()
                    .duration_since(UNIX_EPOCH)
                    .unwrap()
                    .as_secs(),
            });
            return segments;
        }
        
        // Split content into segments
        // This is a simple implementation that splits on paragraph boundaries
        // A more sophisticated implementation would use semantic chunking
        let lines: Vec<&str> = content.lines().collect();
        let mut current_segment = String::new();
        let mut segment_number = 1;
        
        for line in lines {
            // If adding this line would exceed segment size, create a new segment
            if current_segment.len() + line.len() + 1 > self.config.segment_size && !current_segment.is_empty() {
                // Create segment
                segments.push(MemorySegment {
                    id: format!("{}_{}", id_base, segment_number),
                    content: current_segment,
                    source_file: source_file.clone(),
                    domains: domains.clone(),
                    priority: 10,
                    timestamp: SystemTime::now()
                        .duration_since(UNIX_EPOCH)
                        .unwrap()
                        .as_secs(),
                });
                
                // Start new segment
                segment_number += 1;
                
                // Include overlap from previous segment if enabled
                if self.config.segment_overlap > 0 && !segments.is_empty() {
                    let prev_segment = &segments[segments.len() - 1].content;
                    let overlap_start = prev_segment.len().saturating_sub(self.config.segment_overlap);
                    let overlap = &prev_segment[overlap_start..];
                    current_segment = overlap.to_string();
                } else {
                    current_segment = String::new();
                }
            }
            
            // Add line to current segment
            if !current_segment.is_empty() {
                current_segment.push('\n');
            }
            current_segment.push_str(line);
        }
        
        // Add final segment if not empty
        if !current_segment.is_empty() {
            segments.push(MemorySegment {
                id: format!("{}_{}", id_base, segment_number),
                content: current_segment,
                source_file: source_file.clone(),
                domains: domains.clone(),
                priority: 10,
                timestamp: SystemTime::now()
                    .duration_since(UNIX_EPOCH)
                    .unwrap()
                    .as_secs(),
            });
        }
        
        segments
    }
    
    // Format memory segments to final output
    pub fn format_memory_segments(&self, segments: &[MemorySegment], format: &str) -> String {
        self.debug_log(&format!("Formatting {} segments to {}", segments.len(), format));
        
        match format.to_lowercase().as_str() {
            "json" => {
                serde_json::to_string_pretty(segments).unwrap_or_else(|_| "[]".to_string())
            }
            "markdown" => {
                let mut result = String::new();
                
                // Group segments by type
                let mut core_segments = Vec::new();
                let mut learning_segments = Vec::new();
                let mut context_segments = Vec::new();
                
                for segment in segments {
                    if segment.source_file.contains("MEMORY.md") {
                        core_segments.push(segment);
                    } else if segment.source_file.contains("ContinuousLearning.md") {
                        learning_segments.push(segment);
                    } else {
                        context_segments.push(segment);
                    }
                }
                
                // Core memory segments
                if !core_segments.is_empty() {
                    result.push_str("# Core Memory\n\n");
                    for segment in core_segments {
                        result.push_str(&format!("## {}\n\n{}\n\n", segment.id, segment.content));
                    }
                }
                
                // Learning segments
                if !learning_segments.is_empty() {
                    result.push_str("# Continuous Learning\n\n");
                    for segment in learning_segments {
                        result.push_str(&format!("## {}\n\n{}\n\n", segment.id, segment.content));
                    }
                }
                
                // Context segments
                if !context_segments.is_empty() {
                    result.push_str("# Context-Specific Memory\n\n");
                    for segment in context_segments {
                        result.push_str(&format!("## {}\n\n{}\n\n", segment.id, segment.content));
                    }
                }
                
                result
            }
            "text" => {
                let mut result = String::new();
                
                for segment in segments {
                    result.push_str(&format!("--- {} ---\n", segment.id));
                    result.push_str(&segment.content);
                    result.push_str("\n\n");
                }
                
                result
            }
            _ => format!("Unsupported format: {}", format),
        }
    }
}

// Utility function to sanitize a string for use in filenames
fn sanitize_for_filename(s: &str) -> String {
    s.replace(['/', '\\', ':', '*', '?', '"', '<', '>', '|', ' '], "_")
}

// Main function for testing/demo
pub fn main() {
    // Create a test configuration with immediate persistence
    let mut config = MemoryCacheConfig::default();
    config.persistence_interval = Duration::from_secs(0); // Immediate persistence
    config.debug = true;
    
    // Create the cache
    match MemoryCache::new(config) {
        Ok(cache) => {
            // Create a test entry
            match cache.create_agent_cache("TestAgent", "/test/dir", "Test", "Testing the cache") {
                Ok(entry_id) => {
                    println!("Created cache entry: {}", entry_id);
                    
                    // Get active agents
                    let active_agents = cache.get_active_agents();
                    println!("Active agents: {:?}", active_agents);
                    
                    // Get entry for agent
                    if let Some(entry) = cache.get_entry_for_agent("TestAgent") {
                        println!("Found entry for TestAgent: {:?}", entry);
                    }
                    
                    // Deactivate agent
                    if let Err(e) = cache.deactivate_agent("TestAgent") {
                        println!("Error deactivating agent: {}", e);
                    }
                    
                    println!("TestAgent deactivated");
                }
                Err(e) => {
                    println!("Error creating cache entry: {}", e);
                }
            }
        }
        Err(e) => {
            println!("Error creating cache: {}", e);
        }
    }
}