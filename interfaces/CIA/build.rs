// TL CLI Build Script
// This script runs during the build process to configure the TL CLI

use std::env;
use std::fs;
use std::path::Path;
use std::process::Command;

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=Cargo.toml");
    println!("cargo:rerun-if-changed=src/commands/");
    println!("cargo:rerun-if-changed=src/config/");
    println!("cargo:rerun-if-changed=src/helpers/");
    
    // Get the output directory
    let out_dir = env::var("OUT_DIR").unwrap();
    
    // Generate version information
    generate_version_info(&out_dir);
    
    // Generate command registry
    generate_command_registry(&out_dir);
    
    // Configure target-specific features
    configure_target_features();
}

/// Generate version information from git
fn generate_version_info(out_dir: &str) {
    // Get the git commit hash
    let git_hash = Command::new("git")
        .args(&["rev-parse", "--short", "HEAD"])
        .output()
        .map(|output| String::from_utf8_lossy(&output.stdout).trim().to_string())
        .unwrap_or_else(|_| "unknown".to_string());
    
    // Get the git branch
    let git_branch = Command::new("git")
        .args(&["rev-parse", "--abbrev-ref", "HEAD"])
        .output()
        .map(|output| String::from_utf8_lossy(&output.stdout).trim().to_string())
        .unwrap_or_else(|_| "unknown".to_string());
    
    // Write the version information to a file that will be included at compile time
    let version_info = format!(
        "pub const GIT_HASH: &str = \"{}\";\n\
         pub const GIT_BRANCH: &str = \"{}\";\n\
         pub const BUILD_TIMESTAMP: &str = \"{}\";\n",
        git_hash,
        git_branch,
        chrono::Utc::now().to_rfc3339()
    );
    
    let version_file_path = Path::new(&out_dir).join("version_info.rs");
    fs::write(&version_file_path, version_info).unwrap();
}

/// Generate command registry from src/commands directory
fn generate_command_registry(out_dir: &str) {
    // Define the command modules to include
    let command_modules = [
        "agent",
        "memory",
        "knowledge",
        "system",
        "debug",
    ];
    
    // Generate imports and registration code
    let mut imports = String::new();
    let mut registrations = String::new();
    let mut executions = String::new();
    
    for module in &command_modules {
        imports.push_str(&format!("use crate::commands::{};\n", module));
        registrations.push_str(&format!("    app = {}::register_commands(app);\n", module));
        executions.push_str(&format!(
            "        \"{}\" => {}::execute_command(sub_matches),\n",
            module, module
        ));
    }
    
    // Create the command registry module
    let registry_content = format!(
        "// Auto-generated command registry\n\
         // Do not edit this file manually\n\n\
         use clap::{{App, ArgMatches}};\n\
         use anyhow::Result;\n\
         {}\n\
         pub fn register_all_commands(app: App) -> App {{\n\
         {}\
             app\n\
         }}\n\n\
         pub fn execute_command(matches: &ArgMatches) -> Result<()> {{\n\
             match matches.subcommand() {{\n\
         {}\
                 _ => {{\n\
                     println!(\"No command specified. Use --help for usage information.\");\n\
                     Ok(())\n\
                 }}\n\
             }}\n\
         }}\n",
        imports, registrations, executions
    );
    
    let registry_file_path = Path::new(&out_dir).join("command_registry.rs");
    fs::write(&registry_file_path, registry_content).unwrap();
}

/// Configure target-specific features
fn configure_target_features() {
    // Get target OS
    let target_os = env::var("CARGO_CFG_TARGET_OS").unwrap_or_else(|_| "unknown".to_string());
    
    // Configure Windows console
    if target_os == "windows" {
        println!("cargo:rustc-cfg=windows_console");
    }
    
    // Configure terminal features
    if target_os == "unix" || target_os == "macos" {
        println!("cargo:rustc-cfg=unix_terminal");
    }
    
    // Link to system libraries if needed
    if target_os == "linux" {
        println!("cargo:rustc-link-lib=dl");
    }
}