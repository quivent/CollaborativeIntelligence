use serde::{Deserialize, Serialize};
use std::time::SystemTime;

/// Status of an agent
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum AgentStatus {
    /// Agent is currently active
    Active,
    /// Agent is inactive
    Inactive
}

impl std::fmt::Display for AgentStatus {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            AgentStatus::Active => write!(f, "Active"),
            AgentStatus::Inactive => write!(f, "Inactive"),
        }
    }
}

/// Agent cache entry
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AgentCacheEntry {
    /// Name of the agent
    pub agent_name: String,
    
    /// Working directory when the agent was activated
    pub directory: String,
    
    /// Who or what initialized the agent
    pub initializer: String,
    
    /// When the agent was activated
    pub timestamp: SystemTime,
    
    /// Intent or purpose of activating the agent
    pub intent: String,
    
    /// Current status of the agent
    pub status: AgentStatus,
    
    /// Indicates if the entry has been modified since last save
    #[serde(skip)]
    pub is_modified: bool,
}

impl AgentCacheEntry {
    /// Create a new agent cache entry
    pub fn new(
        agent_name: &str,
        directory: &str,
        initializer: &str,
        intent: &str,
    ) -> Self {
        AgentCacheEntry {
            agent_name: agent_name.to_string(),
            directory: directory.to_string(),
            initializer: initializer.to_string(),
            timestamp: SystemTime::now(),
            intent: intent.to_string(),
            status: AgentStatus::Active,
            is_modified: true,
        }
    }
    
    /// Format the entry as markdown
    pub fn to_markdown(&self) -> String {
        let timestamp = chrono::DateTime::<chrono::Local>::from(self.timestamp)
            .format("%Y-%m-%d %H:%M:%S")
            .to_string();
        
        format!(
            r#"# Agent Activation Cache

## Metadata
- **Agent:** {}
- **Working Directory:** {}
- **Initializer:** {}
- **Timestamp:** {}

## Intent
{}

## Status
{}

This file was automatically generated by the Agent Cache System and should be immediately integrated into the agent's short-term memory upon activation.
"#,
            self.agent_name,
            self.directory,
            self.initializer,
            timestamp,
            self.intent,
            self.status
        )
    }
}